#[test]
fn denoises_nothing() {
    assert_eq!(unoise("empty", &[], ""), (String::new(), String::new()));
}

#[test]
fn rejects_invalid_arguments() {
    for args in [
        &["--weak-id", "0.5"][..],
        &["--alpha", "x"],
        &["--alpha", "inf"],
        &["--id", "1.5"],
        &["--strand", "minus"],
        &["--maxhits", "2"],
    ] {
        assert_eq!(
            run("args", args, INPUT).0.status.code(),
            Some(2),
            "{args:?}"
        );
    }
    let (output, _) = run("bad", &[], ">a\nACGT\n>b;size=0\nACGT\n");
    assert_eq!(output.status.code(), Some(1));
}
