/// A path in the temporary directory, unique to this test process.
fn temp_path(name: &str) -> PathBuf {
    std::env::temp_dir().join(format!("rsearch-unoise-{}-{name}", std::process::id()))
}

/// Runs unoise with `args` on `input`, its hits written to a file.
fn run(name: &str, args: &[&str], input: &str) -> (Output, String) {
    let (inp, hits) = (
        temp_path(&format!("{name}-in")),
        temp_path(&format!("{name}-hits")),
    );
    std::fs::write(&inp, input).unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_unoise"))
        .arg("-i")
        .arg(&inp)
        .arg("--hits")
        .arg(&hits)
        .args(args)
        .stdin(Stdio::null())
        .output()
        .unwrap();
    let written = std::fs::read_to_string(&hits).unwrap_or_default();
    let _ = std::fs::remove_file(&inp);
    let _ = std::fs::remove_file(&hits);
    (output, written)
}

/// Runs unoise, which must succeed, and returns its centroids and hits.
fn unoise(name: &str, args: &[&str], input: &str) -> (String, String) {
    let (output, hits) = run(name, args, input);
    assert!(
        output.status.success(),
        "unoise failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    (String::from_utf8(output.stdout).unwrap(), hits)
}

