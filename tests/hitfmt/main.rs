//! End-to-end tests of the hitfmt binary.
//!
//! Expected outputs are those vsearch `--usearch_global --notrunclabels
//! --qmask none --dbmask none --strand both --id 0.6 --maxaccepts 3` writes
//! beside its `--uc --uc_allhits` hits, from those hits, the queries and
//! the database. `--alignments` is `--alnout` (without vsearch's opening
//! lines), `--blast6` `--blast6out`, `--userout F` `--userout` with
//! `--userfields F`, `--sam` `--samout` (and `--sam-header` `--samheader`,
//! but for rsearch's own `@PG` line), `--fasta-pairs`, `--qsegs` and
//! `--tsegs` `--fastapairs`, `--qsegout` and `--tsegout` with
//! `--fasta_width 0`. The search's own options (`--iddef`, `--n-mismatch`,
//! `--match`, `--mismatch`, `--gapopen`, `--gapext`) are given to hitfmt
//! too, as the hits do not hold them.

