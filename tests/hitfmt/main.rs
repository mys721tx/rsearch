/// Runs hitfmt with `args` on `hits`, the queries and the database.
fn hitfmt(name: &str, hits: &str, args: &[&str]) -> Output {
    let paths = ["hits", "q", "db"].map(|p| temp_path(&format!("{name}-{p}")));
    std::fs::write(&paths[0], hits).unwrap();
    std::fs::write(&paths[1], QUERIES).unwrap();
    std::fs::write(&paths[2], DB).unwrap();
    let path = |i: usize| paths[i].to_str().unwrap().to_string();
    let output = Command::new(env!("CARGO_BIN_EXE_hitfmt"))
        .args([path(0), "-i".into(), path(1), "--db".into(), path(2)])
        .args(args)
        .stdin(Stdio::null())
        .output()
        .unwrap();
    for path in &paths {
        let _ = std::fs::remove_file(path);
    }
    output
}

/// Runs hitfmt, which must succeed, and returns what it wrote.
fn format(name: &str, hits: &str, args: &[&str]) -> String {
    let output = hitfmt(name, hits, args);
    assert!(
        output.status.success(),
        "hitfmt failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout).unwrap()
}

